"""Synthetic attack certificates on graphs that ARE unit-distance graphs (so any 'proof' that
they are not must be wrong), each built so that exactly one check of the verifier stands
between it and an ACCEPT.  Used by redteam11.py (verified with the order check off: these graphs have 3 or 4 vertices)."""
