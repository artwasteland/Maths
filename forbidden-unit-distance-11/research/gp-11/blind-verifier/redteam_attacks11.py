def g6_encode(n, E):
    bits = [1 if (i, j) in E else 0 for j in range(1, n) for i in range(j)]
    while len(bits) % 6:
        bits.append(0)
    out = chr(63 + n)
    for k in range(0, len(bits), 6):
        v = 0
        for b in bits[k:k + 6]:
            v = (v << 1) | b
        out += chr(63 + v)
    return out


def ser_poly(p):
    """fmpq_mpoly -> canonical sparse term list (strictly increasing lex exponent order)."""
    items = sorted(((tuple(int(e) for e in k), fmpq(v)) for k, v in p.to_dict().items()))
    return [[str(v.p) if v.q == 1 else '%d/%d' % (v.p, v.q), list(k)] for k, v in items if v != 0]


class TP:
    """A polynomial together with its cofactor expansion in named generators."""

    def __init__(self, p, cof):
        self.p, self.cof = p, cof

    def __add__(self, o):
        c = dict(self.cof)
        for k, v in o.cof.items():
            c[k] = c.get(k, 0) + v
        return TP(self.p + o.p, c)

    def __sub__(self, o):
        return self + o.scale(-1)

    def scale(self, q):
        return TP(self.p * q, {k: v * q for k, v in self.cof.items()})


def forced_distance_identity(ctx, X, Y, A, B, P, Q, gkeys):
    """Frame A=(0,0), B=(1,0); P, Q adjacent to A and B; K = |P-Q|^2 - 1.  Returns cofactors
    with sum c_k g_k = 1 (P and Q are forced to (1/2, +-sqrt3/2), at distance 0 or sqrt3)."""
    def d2(u, v):
        return (X(u) - X(v)) ** 2 + (Y(u) - Y(v)) ** 2
    gens = {gkeys['PA']: d2(P, A) - 1, gkeys['PB']: d2(P, B) - 1, gkeys['QA']: d2(Q, A) - 1,
            gkeys['QB']: d2(Q, B) - 1, gkeys['PQ']: d2(P, Q) - 1}
    G = {k: TP(v, {k: ctx.constant(1)}) for k, v in gens.items()}
    half = fmpq(1, 2)
    LP = G[gkeys['PA']] - G[gkeys['PB']]            # 2 xP - 1
    LQ = G[gkeys['QA']] - G[gkeys['QB']]
    YP = G[gkeys['PA']] - LP.scale((X(P) + half) * half)   # yP^2 - 3/4
    YQ = G[gkeys['QA']] - LQ.scale((X(Q) + half) * half)
    dx = X(P) - X(Q)
    M = ((LP - LQ).scale(dx * half) + YP + YQ - G[gkeys['PQ']]).scale(half)   # yP yQ - 1/4
    N = YP.scale(YQ.p) + YP.scale(fmpq(3, 4)) + YQ.scale(fmpq(3, 4))         # yP^2 yQ^2 - 9/16
    one = (M.scale(Y(P) * Y(Q) + fmpq(1, 4)) - N).scale(2)
    assert one.p == 1, one.p
    total = ctx.constant(0)
    for k, c in one.cof.items():
        total += c * gens[k]
    assert total == 1
    return one.cof, gens


def diamond():
    # vertices 0,1,2,3; edges all but 2-3 (two equilateral triangles on 01): a UDG
    return 4, {(0, 1), (0, 2), (0, 3), (1, 2), (1, 3)}


def attack_null_nonedge_frame():
    n, E = diamond()
    # frame on the NON-edge (2,3): p2=(0,0), p3=(1,0); variables x_0,y_0,x_1,y_1
    ctx = fmpq_mpoly_ctx.get(('x_0', 'y_0', 'x_1', 'y_1'), 'lex')
    x0, y0, x1, y1 = ctx.gens()
    zero, one = ctx.constant(0), ctx.constant(1)
    X = {0: x0, 1: x1, 2: zero, 3: one}.get
    Y = {0: y0, 1: y1, 2: zero, 3: zero}.get
    keys = {'PA': 'e:0,2', 'PB': 'e:0,3', 'QA': 'e:1,2', 'QB': 'e:1,3', 'PQ': 'e:0,1'}
    cof, _ = forced_distance_identity(ctx, X, Y, 2, 3, 0, 1, keys)
    cert = {'type': 'null', 'frame': [2, 3], 'sat': [],
            'cofactors': {k: ser_poly(v) for k, v in cof.items()}}
    return {'g6': g6_encode(n, E), 'verdict': 'refuted', 'cert': cert}


def attack_null_extra_generator():
    n, E = diamond()
    # frame on the edge (0,1); P=2, Q=3; the illegal generator e:2,3 (a non-edge set to 1)
    ctx = fmpq_mpoly_ctx.get(('x_2', 'y_2', 'x_3', 'y_3'), 'lex')
    x2, y2, x3, y3 = ctx.gens()
    zero, one = ctx.constant(0), ctx.constant(1)
    X = {0: zero, 1: one, 2: x2, 3: x3}.get
    Y = {0: zero, 1: zero, 2: y2, 3: y3}.get
    keys = {'PA': 'e:0,2', 'PB': 'e:1,2', 'QA': 'e:0,3', 'QB': 'e:1,3', 'PQ': 'e:2,3'}
    cof, gens = forced_distance_identity(ctx, X, Y, 0, 1, 2, 3, keys)
    # sanity: the legal generators regenerated by the verifier agree with ours
    sysm = V.System(n, frozenset(E), [0, 1], [])
    for k in ('e:0,2', 'e:0,3', 'e:1,2', 'e:1,3'):
        assert sysm.ctx.from_dict(gens[k].to_dict()) == sysm.gens[k]
    assert 'e:2,3' not in sysm.gens
    cert = {'type': 'null', 'frame': [0, 1], 'sat': [],
            'cofactors': {k: ser_poly(v) for k, v in cof.items()}}
    return {'g6': g6_encode(n, E), 'verdict': 'refuted', 'cert': cert}


def attack_null_extra_generator_dag():
    rec = attack_null_extra_generator()
    c = rec['cert']
    rec['cert'] = {'type': 'null-dag', 'frame': c['frame'], 'sat': [],
                   'rows': [{'poly': [['1', [0, 0, 0, 0]]], 'cofactors': c['cofactors']}]}
    return rec


