SQ3 = [-3, 0, 1]
SQ3_INTERVAL = ['32592/18817', '18817/10864']


def ser_real(p, deg):
    cs = p.coeffs()
    if not cs:
        cs = [fmpq(0)]
    return [str(c.p) if c.q == 1 else '%d/%d' % (c.p, c.q) for c in [fmpq(x) for x in cs]][:deg]


def ser_c(x, deg):
    if x[1].is_zero():
        return ser_real(x[0], deg)
    return {'re': ser_real(x[0], deg), 'im': ser_real(x[1], deg)}


def ser_rows(F, rows):
    return [[ser_c(e, F.deg) for e in r] for r in rows]


def node(F, n, E, rows, move, children):
    return {'A': ser_rows(F, rows), 'children': children,
            'edges': [list(e) for e in sorted(E)], 'move': move}


def attack_tree_l1b_unit():
    # C4 = 0-1-2-3-0 is a UDG (a unit square).  Rhombus: f0 - f1 = f3 - f2, omega = 1.
    n, E = 4, {(0, 1), (1, 2), (2, 3), (0, 3)}
    F = V.rational_field()
    rows = V.rhombus_rows(F, n, E)
    t = node(F, n, E, rows, {'kind': 'L1b', 'edges': [[0, 1], [3, 2]], 'omega': [1]}, [])
    return {'g6': g6_encode(n, E), 'verdict': 'refuted',
            'cert': {'type': 'tree', 'witness': {'field': {'interval': [-1, 1], 'minpoly': [0, 1]}, 'tree': t}}}


def attack_tree_l1c_positive():
    # K3 is a UDG.  x - y + z = 0 holds identically; discriminant 3 > 0.
    n, E = 3, {(0, 1), (0, 2), (1, 2)}
    F = V.rational_field()
    t = node(F, n, E, [], {'kind': 'L1c', 'edges': [[0, 1], [0, 2], [1, 2]],
                           'coefficients': [[1], [-1], [1]]}, [])
    return {'g6': g6_encode(n, E), 'verdict': 'refuted',
            'cert': {'type': 'tree', 'witness': {'field': {'interval': [-1, 1], 'minpoly': [0, 1]}, 'tree': t}}}


def attack_tree_l1a_square():
    n, E = 4, {(0, 1), (1, 2), (2, 3), (0, 3)}
    F = V.rational_field()
    rows = V.rhombus_rows(F, n, E)
    t = node(F, n, E, rows, {'kind': 'L1a', 'pair': [0, 2]}, [])
    return {'g6': g6_encode(n, E), 'verdict': 'refuted',
            'cert': {'type': 'tree', 'witness': {'field': {'interval': [-1, 1], 'minpoly': [0, 1]}, 'tree': t}}}


def attack_tree_l2_nonunit():
    """Diamond (a UDG).  L3 on triangle 012 gives f2 - f3 = -+ i sqrt3 (f0 - f1): the NON-edge
    23 has length sqrt3.  An L2 that adds edge 23 anyway (|omega| = 1/sqrt3) turns the graph
    into K4, which L1a then 'refutes'.  Everything is exact except the L2 modulus."""
    n, E = diamond()
    F = V.Field([fmpq(c) for c in SQ3], V.parse_rat_str(SQ3_INTERVAL[0], 'lo'),
                V.parse_rat_str(SQ3_INTERVAL[1], 'hi'))
    th = fmpq_poly([0, 1])
    one = F.c(F.one)
    root_rows = V.rhombus_rows(F, n, E)
    a, b, c = one, F.c(-F.one), one
    s = F.cnorm2(a) + F.cnorm2(b) - F.cnorm2(c)
    d = th  # sqrt 3; D = 4 - 1 = 3
    children = []
    for sgn in (1, -1):
        coef1 = F.cmul(F.c(s, sgn * d), a)
        row = V.vadd(F, V.disp(F, n, 0, 1, coef1), V.disp(F, n, 0, 2, F.cscale(F.red(2 * F.cnorm2(a)), b)))
        rows = root_rows + [row]
        sp = V.RowSpace(F, n, rows)
        # find omega with (e0 - e1) - omega (e2 - e3) in the space
        r1 = sp.reduce(V.disp(F, n, 0, 1, one))
        r2 = sp.reduce(V.disp(F, n, 2, 3, one))
        j = next(k for k, x in enumerate(r2) if not F.ciszero(x))
        omega = F.cmul(r1[j], F.cinv(r2[j]))
        rel = V.vadd(F, V.disp(F, n, 0, 1, one), V.disp(F, n, 2, 3, F.cneg(omega)))
        assert sp.contains(rel)
        n2 = F.cnorm2(omega)
        assert not F.red(n2 - F.one).is_zero()     # |omega|^2 = 1/3
        E2 = set(E) | {(2, 3)}
        rows2 = rows + V.rhombus_rows(F, n, E2)
        sp2 = V.RowSpace(F, n, rows2)
        assert sp2.contains(V.disp(F, n, 0, 1, one))   # K4 collapses: L1a is genuinely valid
        leaf = node(F, n, E2, rows2, {'kind': 'L1a', 'pair': [0, 1]}, [])
        children.append(node(F, n, E, rows, {'kind': 'L2', 'edges': [[0, 1], [2, 3]],
                                             'omega': ser_c(omega, F.deg)}, [leaf]))
    t = node(F, n, E, root_rows, {'kind': 'L3', 'edges': [[0, 1], [0, 2], [1, 2]],
                                  'coefficients': [[1], [-1], [1]], 'd': [0, 1]}, children)
    return {'g6': g6_encode(n, E), 'verdict': 'refuted',
            'cert': {'type': 'tree', 'witness': {'field': {'interval': SQ3_INTERVAL, 'minpoly': SQ3}, 'tree': t}}}


def attack_tree_l2_nonunit_control():
    """The same tree with the L2 moves relabelled L1b and the leaves removed: the relation is
    exact and |omega| != 1, but the second pair 2-3 is a NON-edge, so L1b must also refuse."""
    rec = attack_tree_l2_nonunit()
    for ch in rec['cert']['witness']['tree']['children']:
        ch['move']['kind'] = 'L1b'
        ch['children'] = []
    return rec


