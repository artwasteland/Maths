"""Write INDEPENDENT-CHECKS.md from the JSON outputs of the checks run after the result. No number is typed by hand.

usage: python write_independent_checks.py RUNDIR G4DIR OUT.md

RUNDIR holds independent-audit.json, vf2-spot.json, redteam.json, embed-part*.json and, when the blind second verifier
has run, blind/verdicts.jsonl and blind/redteam.json. G4DIR is the G4 run (report.json, summary.json).
"""
import sys, json, os, glob
from collections import Counter

RUN, G4, OUT = sys.argv[1:4]
J = lambda p: json.load(open(p))
audit, vf2, red = J(f"{RUN}/independent-audit.json"), J(f"{RUN}/vf2-spot.json"), J(f"{RUN}/redteam.json")
parts = [J(p) for p in sorted(glob.glob(f"{RUN}/embed-part*.json"))]
g4r, g4s = J(f"{G4}/report.json"), J(f"{G4}/summary.json")
fmt = lambda n: f"{n:,}"

for need, what in ((audit["verdict"] == "INDEPENDENT AUDIT PASS" and not audit["alarms"], "audit"),
                   (vf2["verdict"] == "INDEPENDENT AUDIT PASS" and not vf2["alarms"], "vf2"),
                   (red["all_controls_behaved"], "red-team controls"),
                   (g4r["status"] == "ACCEPT" and not g4r["conditional"] and g4r["direct_rejections"] == 0, "G4 run")):
    if not need:
        sys.exit(f"refusing: {what} did not pass; this document reports passes only after they happen")

inp, mn, ep, cc = audit["input"], audit["minimality"], audit["embeddings_and_pointers"], audit["cross_consistency"]
vs = vf2["vf2_spot"]
p1 = next(c for c in red["controls"] if c["control"].startswith("P1"))
reds = [c for c in red["controls"] if "red" in c]
rows = [r for p in parts for r in p["rows"]]
emb_hits = [r["g6"] for r in rows if r["hits"]]
near_members = sum(1 for r in rows if r["near_misses"])
near_total = sum(r["near_misses"] for r in rows)
me_found = sum(r["minus_edge"]["found"] for r in rows)
la = [r["lookalike"] for r in rows if "lookalike" in r]
la_found = sum(x["found"] for x in la)
la_same = sum(x["kind"] == "same_degrees" for x in la)
by_m = {}
for r in rows:
    b = by_m.setdefault(r["edges"], Counter())
    b["members"] += 1; b["hits"] += r["hits"] > 0
    b["me"] += r["minus_edge"]["found"]; b["la_n"] += "lookalike" in r; b["la"] += r.get("lookalike", {}).get("found", False)
budget = parts[0]["budget_per_member"]
L = []
w = L.append
w("# GP-10: independent checks after the result")
w("")
w("Generated by `tools/write_independent_checks.py` from the JSON files in `runs/independent-checks-2026-09-25/` and")
w("`runs/G4-second-certificates-2026-09-25/`. Every number below is read from those files.")
w("")
w("`RESULT.md` rests on one checker (`check/gp10check.py` with its kernel): every certificate, every count and the")
w("minimal list went through it. The checks here were run afterwards to find out whether anything in the result")
w("depends on that one implementation being right. Each one avoids the checker in a different way, and each was")
w("made to go red on purpose before its green was believed.")
w("")
w("## 1. An independent audit of the records (`tools/independent_audit.py`)")
w("")
w("Written against CONTRACT.md's definitions with networkx, pynauty and mpmath only; it imports nothing from `check/`,")
w("`drive/` or the producers. It trusts the records' verdicts only where stated, and tests them against each other.")
w("")
w(f"- **Input.** {fmt(inp['B10'])} graphs, {fmt(inp['distinct_iso_classes'])} distinct isomorphism classes (nauty certificates); the")
w(f"  records cover B10 exactly: {fmt(inp['verdicts']['embedded'])} embedded, {fmt(inp['verdicts']['refuted'])} refuted.")
w(f"- **Minimality, recounted from scratch.** Every one-edge deletion of every refuted graph was rebuilt and looked up")
w(f"  by its nauty certificate (never through the driver's poset). {mn['recounted_minimal']} refuted graphs have every")
w(f"  biconnected deletion embedded; equal to L10.g6: {'yes' if mn['equals_L10'] else 'NO'}. The other {mn['refuted_not_minimal']}")
w(f"  refuted graphs are not minimal. Biconnected deletions missing from B10: {mn['deletions_missing_from_B10']}.")
w(f"- **Every exact embedding, re-evaluated.** {fmt(ep['exact_embeddings'])} embeddings: the root of each minimal polynomial found by")
w(f"  bisection at {ep['digits']} digits, every coordinate evaluated there. Worst edge-length residue {ep['worst_edge_error']};")
w(f"  at 240 digits it falls to {p1['worst_edge_error_240']}, so the residue is rounding and the edges are exactly unit.")
w(f"  Smallest distance between two points of any embedding: {ep['smallest_point_gap']}.")
rt = ep["record_types"]
w(f"- **Every pointer.** {fmt(rt.get('embedded/super', 0))} subgraph-of-an-embedded-graph pointers and {rt.get('refuted/sub', 0)}")
w(f"  contains-a-refuted-graph pointers: the map is injective and edge-preserving in the contract's direction, the")
w(f"  target carries the required verdict, and every chain ends at a non-pointer certificate. Broken chains:")
w(f"  {ep['bad_pointer_chains']}.")
w(f"- **Cross-consistency.** The graphs of B10 obtained from an L10 member by adding edges number {cc['upset_of_L10_in_B10']};")
w(f"  the refuted graphs number {cc['refuted']}; the two sets are {'equal' if cc['upset_equals_refuted'] else 'NOT equal'}. So no")
w(f"  embedded graph contains a forbidden one, and every refuted graph contains a minimal one.")
w(f"- **The same, by a method with no canonical forms.** VF2 subgraph monomorphism, the {vs['densest_embedded_scanned']} densest")
w(f"  embedded graphs ({vs['edge_range'][0]} to {vs['edge_range'][1]} edges, of {fmt(vs['of_embedded'])}) against every L10 member:")
w(f"  {fmt(vs['pairs_tested'])} pairs, {vs['hits']} containments. Capped at {vs['densest_embedded_scanned']} hosts (about 15 s each).")
w("")
w("## 2. Red on purpose (`tools/independent_audit_redteam.py`)")
w("")
w("Each control changes one thing in a copy of the inputs; it passes only if the audit fails with the alarm that names")
w("the change.")
w("")
w("| control | expected alarm | outcome |")
w("|---|---|---|")
for c in reds:
    w(f"| {c['control']} | {c['expected_alarm']} | {'red, as required' if c['red'] else 'STAYED GREEN'} |")
w(f"| {p1['control']} | (must pass, residue must shrink) | {'passed; worst residue ' + p1['worst_edge_error_240'] if p1['passes_and_shrinks'] else 'FAILED'} |")
w("")
w(f"{sum(c['red'] for c in reds)} of {len(reds)} mutations turned the audit red with the named alarm.")
w("")
w("## 3. Trying to embed the 324 anyway (`tools/embed_redteam.py`)")
w("")
w("If a refutation certificate were wrong, its graph would have an embedding, and a hard enough numerical search")
w("might find it. This one uses numpy only: one angle per spanning-tree edge (tree edges are unit by construction),")
w(f"batched Levenberg-Marquardt from {fmt(budget)} random starts per graph, and a candidate counts only if refinement at")
w("50 digits drives every edge residue below 1e-35 while no two points come closer than 1e-6. A search that finds")
w("nothing proves nothing unless its power is measured, so the same rule, with the same budget as a ceiling, was spent on two")
w("embeddable controls per member: the member minus one edge (embeddable by minimality), and an embedded B10 graph")
w("with the same number of edges.")
w("")
w(f"- **Members:** {len(rows)} searched, **{len(emb_hits)} embeddings found**.")
rec_gaps = [float(g) for r in rows for g in r["near_miss_gaps"]]
w(f"- **Near-misses:** {fmt(near_total)} float candidates on {near_members} members passed the fast filter, and none")
w(f"  survived refinement. Of the {fmt(len(rec_gaps))} whose refined gap was recorded (up to three per member), the largest")
if max(rec_gaps) < 1e-6:
    w(f"  remaining distance between two points was {max(rec_gaps):.1e}: each slid into a collision, which is how these")
    w("  graphs fail to embed.")
else:
    big = sum(g >= 1e-6 for g in rec_gaps)
    w(f"  remaining distance between two points was {max(rec_gaps):.1e}. {big} kept a gap above 1e-6 but their residue")
    w("  stayed above 1e-35, so refinement did not reach a solution; the rest slid into a collision.")
w(f"- **Controls:** member minus an edge, {me_found} of {len(rows)} found; look-alike with the same edge count, {la_found}")
w(f"  of {len(la)} found ({la_same} of them with the same degree sequence as their member).")
w("")
w("| edges | members | members embedded | minus-edge controls found | look-alike controls found |")
w("|---|---|---|---|---|")
for m in sorted(by_m):
    b = by_m[m]
    w(f"| {m} | {b['members']} | {b['hits']} | {b['me']} of {b['members']} | {b['la']} of {b['la_n']} |")
w("")
w("This is evidence, not proof: it could find a counterexample to a certificate, and on graphs that do embed it finds")
w("one at the rate in the table.")
w("")
w("## 4. A second certificate of a different type (gate G4)")
w("")
cov = g4s["primary_types_covered"]
w(f"{g4s['checker_accepted']} of {g4s['L10']} L10 members have a second refutation, of a different certificate type from the")
w(f"one in the final records, accepted by the checker (run `{os.path.basename(G4.rstrip('/'))}`: {g4r['status']},")
w(f"{g4r['counts']['refuted']} refuted, {g4r['counts']['unknown']} unknown, {g4r['direct_rejections']} rejections). Alternates by type:")
w(", ".join(f"{k} {v}" for k, v in sorted(g4s["alternate_types_accepted"].items(), key=lambda x: -x[1])) + ".")
w("Members covered, by the type of their primary certificate: " +
  ", ".join(f"{k} {v}" for k, v in sorted(cov.items(), key=lambda x: -x[1])) + ".")
w("This is a count, not a requirement: both certificates go through the same checker, but through different branches")
w("of it.")
w("")
bl = f"{RUN}/blind/verdicts.jsonl"
if os.path.exists(bl):
    rd = lambda p: [json.loads(l) for l in open(p) if l.strip()]
    vb = rd(bl)
    ct = Counter((v["type"], v["verdict"]) for v in vb)
    rerun = rd(f"{RUN}/blind/verdicts-rerun-by-supervisor.jsonl")
    same = {v["g6"]: v["verdict"] for v in rerun} == {v["g6"]: v["verdict"] for v in vb}
    mnames = J(f"{RUN}/blind/supervisor-mutation-names.json")
    mout = rd(f"{RUN}/blind/supervisor-mutations-verdicts.jsonl")
    g74 = rd(f"{RUN}/blind/gp74-verdicts.jsonl")
    g74c = Counter(v["type"] for v in g74 if v["verdict"] == "ACCEPT")
    ind = J(f"{RUN}/blind/gp74-induction.json")
    brt = J(f"{RUN}/blind/redteam.json")
    neg = sum(v["negative_controls"] for v in brt["summary_by_type"].values())
    negr = sum(v["rejected"] for v in brt["summary_by_type"].values())
    w("## 5. A second verifier, written blind (`blind-verifier/`)")
    w("")
    w("Built by a Claude agent (the official checker was built by codex, so the two come from different model families)")
    w("from the written specification only, in a directory holding no checker, kernel or producer code;")
    w("`blind-verifier/REPORT.md` describes what it implements and every reading of the spec it chose.")
    w("")
    w("| certificate type | ACCEPT | REJECT | UNSUPPORTED |")
    w("|---|---|---|---|")
    for t_ in sorted({v["type"] for v in vb}):
        w(f"| {t_} | {ct[(t_, 'ACCEPT')]} | {ct[(t_, 'REJECT')]} | {ct[(t_, 'UNSUPPORTED')]} |")
    w("")
    w(f"- **Its red controls:** {negr} of {neg} mutated certificates rejected, the unmutated originals accepted in the same")
    w("  run (`blind/redteam.json`).")
    w(f"- **Re-run by the supervisor:** verdicts {'identical' if same else 'DIFFERENT'} on all {len(rerun)} records.")
    w(f"- **Five mutations it never saw,** designed by the supervisor: " +
      "; ".join(f"{n} ({o['verdict']})" for n, o in zip(mnames, mout)) + ".")
    w(f"- **The premise it leans on, closed.** Its TU acceptances may end at a Globus-Parshall graph, which it takes as")
    w(f"  forbidden. Run over the certificates that re-derived all {ind['gp74_minimal_graphs']} GP graphs from an empty list")
    w(f"  (runs B4p-F3 to B9p-F8), it accepts {sum(v['verdict'] == 'ACCEPT' for v in g74)} of {len(g74)} (" +
      ", ".join(f"{k} {v}" for k, v in sorted(g74c.items(), key=lambda x: -x[1])) + "); every one of their")
    w(f"  {ind['gp74_tu_certificates']} TU certificates cites only a strictly smaller forbidden graph, so the induction on")
    w(f"  the number of vertices is not circular ({len(ind['violations'])} violations; `blind/gp74-induction.json`).")
    w("")
mp = f"{RUN}/modp-identities-L10.json"
if os.path.exists(mp):
    m1, m2 = J(mp), J(f"{RUN}/modp-identities-GP74.json")
    if m1["verdict"] != "MODP PASS" or m2["verdict"] != "MODP PASS":
        sys.exit("refusing: the mod-p identity check did not pass")
    k1 = {k[:-3]: v for k, v in m1["counts"].items() if k.endswith(" ok")}
    w("## 6. Every polynomial identity, without FLINT (`tools/modp_identities.py`)")
    w("")
    w("Both verifiers expand the polynomial identities in python-flint. This check shares no code with FLINT, sympy or")
    w("either verifier: it regenerates each system from the graph6 string and evaluates both sides of every identity at")
    w(f"{m1['points_per_prime']} random points modulo each of {' and '.join(m1['primes'])}, in Python integers. A false identity of degree d")
    w("survives a random point with probability at most d/p, so none can pass unnoticed here in practice.")
    w("")
    w(f"- **The 324:** " + ", ".join(f"{k} {v}" for k, v in sorted(k1.items(), key=lambda x: -x[1])) +
      f" certificates, {fmt(m1['identities_checked_per_point'])} identities per point (every cofactor sum, every derivation")
    w(f"  row, every sum-of-squares decomposition): {len(m1['failures'])} failures.")
    w(f"- **The 74 GP certificates:** {sum(v for k, v in m2['counts'].items() if k.endswith(' ok'))} polynomial ones,"
      f" {m2['identities_checked_per_point']} identities per point: {len(m2['failures'])} failures.")
    w(f"- **Red controls:** {sum(x['red'] for x in m1['red_controls'])} of {len(m1['red_controls'])} mutations (a coefficient changed, a")
    w("  term dropped, a row emptied, an SOS weight or constant changed, a frame on a non-edge) failed as required.")
    w("- Not an identity, so not covered here: a Sturm certificate's claim that its univariate f has no real root. That")
    w("  count is made by the official checker, by the blind verifier, and by sympy's `count_roots` inside the blind one.")
    w("")
w("## What these checks do not cover")
w("")
if os.path.exists(bl):
    w("- The refutations are checked by two implementations from different model families, built from the same written")
    w("  lemmas (`PROOFS.md`, the u(22) gadget proofs, AMP Section 4): a mistake in a lemma itself would pass both.")
    w("  Both do their exact polynomial arithmetic in python-flint; every identity was also re-checked without it")
    w("  (section 6).")
else:
    w("- The soundness of the refutation certificates themselves is checked by the official checker; sections 3 and 4")
    w("  add evidence and second certificates.")
w("- B10's completeness was established at gate G0 (geng's biconnected count matches OEIS A002218, and an independent")
w("  C matcher reproduced the F9 filter byte for byte); nothing here re-derives it.")
w("- The audit's pynauty and the pipeline's canonical labelling both come from nauty.")
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", OUT, len(L), "lines")
