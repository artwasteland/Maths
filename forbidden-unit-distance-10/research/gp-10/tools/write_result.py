"""Gate G6: write RESULT.md from the B10 checker's own output, and refuse while any gate is open.

usage: python write_result.py CHECKED_DIR RECORDS.jsonl OUT.md

CHECKED_DIR is the checker's output directory for the B10-profile run (report.json, L10.g6). RECORDS.jsonl is the run's
records file (streamed only to name the certificate type behind each L10 member). Every number in the output comes
from those files. Refuses (exit 2) unless: status ACCEPT, profile B10, reason verified, unknown count 0, conditional
false, no conditional minimal graphs, no direct rejections, eight controls present, and the committed G5 response exists.
"""
import sys, os, json
from collections import Counter

checked, records_path, out_path = sys.argv[1:4]
here = os.path.dirname(os.path.abspath(__file__))
report = json.load(open(os.path.join(checked, "report.json")))


def refuse(why):
    print("REFUSED:", why)
    sys.exit(2)


if report.get("status") != "ACCEPT" or report.get("reason") != "verified":
    refuse(f"checker status {report.get('status')} / {report.get('reason')}")
if report.get("profile") != "B10":
    refuse(f"profile {report.get('profile')} is not B10")
if report["counts"].get("unknown", 1) != 0:
    refuse(f"{report['counts'].get('unknown')} unknown graphs (G3 open)")
if report.get("conditional") is not False or report.get("conditional_minimal"):
    refuse("conditional result (G3/G4 open)")
if report.get("direct_rejections"):
    refuse(f"{report['direct_rejections']} direct rejections")
if sorted((report.get("controls") or {}).keys()) != sorted(["B4p", "B5p", "B6p", "B7p", "B8p", "B9p", "named", "regressions"]):
    refuse(f"controls present: {sorted((report.get('controls') or {}).keys())}")
if not os.path.exists(os.path.join(here, "..", "G5-RESPONSE.md")):
    refuse("G5 response missing")

L10 = [l.strip() for l in open(os.path.join(checked, report.get("minimal_file", "L10.g6"))) if l.strip()]
if len(L10) != report["minimal_count"] or sorted(L10) != sorted(report["minimal"]):
    refuse("L10.g6 disagrees with report.json")
if sum(report["counts"].values()) != report["input_count"]:
    refuse("counts do not sum to the input count")


def edges(g6):
    n = ord(g6[0]) - 63
    bits = []
    for ch in g6[1:]:
        v = ord(ch) - 63
        bits += [(v >> (5 - i)) & 1 for i in range(6)]
    out, k = [], 0
    for j in range(1, n):
        for i in range(j):
            if bits[k]:
                out.append((i, j))
            k += 1
    return n, out


want, ctype = set(L10), {}
with open(records_path, "rb") as f:
    for raw in f:
        r = json.loads(raw)
        if r.get("g6") in want:
            ctype[r["g6"]] = (r.get("cert") or {}).get("type") or "?"
if set(ctype) != want:
    refuse("some L10 member has no record in the records file")

by_m, by_min, by_max = Counter(), Counter(), Counter()
rows = []
for g in sorted(L10, key=lambda g: (len(edges(g)[1]), g)):
    n, es = edges(g)
    deg = [0] * n
    for i, j in es:
        deg[i] += 1; deg[j] += 1
    by_m[len(es)] += 1; by_min[min(deg)] += 1; by_max[max(deg)] += 1
    rows.append((g, len(es), "".join(str(d) for d in sorted(deg, reverse=True)), ctype[g]))

c = report["counts"]
lines = [
    "# GP-10 result: the minimal forbidden unit-distance graphs on 10 vertices",
    "",
    "Generated by `tools/write_result.py` from the B10-profile checker output alone; every number below is read from",
    "the checker's report or its L10 list. Nothing here is a producer's claim.",
    "",
    "## Statement",
    "",
    f"There are exactly **{report['minimal_count']}** minimal forbidden graphs on 10 vertices: 10-vertex graphs that are "
    "not unit-distance graphs but every proper subgraph of which is. With Globus and Parshall's 74 on at most 9 "
    f"vertices, the complete list of minimal forbidden graphs on at most 10 vertices has **{74 + report['minimal_count']}** members.",
    "",
    "## The run",
    "",
    f"- Candidates: {report['input_count']:,} biconnected 10-vertex graphs with no F9 member as a subgraph "
    f"(`data/B10.g6`, sha256 `{report['input_sha256']}`).",
    f"- Decided: {c['embedded']:,} embedded, {c['refuted']:,} refuted, {c['unknown']} unknown. Refuted but not minimal: "
    f"{report['nonminimal_count']}. Direct rejections: {report['direct_rejections']}.",
    f"- Checker `{report['checker_sha256']}`, kernel `{report['kernel_sha256']}`; trusted data "
    + ", ".join(f"{k} `{v[:16]}…`" for k, v in sorted(report["trusted_data_sha256"].items())) + ".",
    f"- Controls re-verified inside the same run: {', '.join(sorted(report['controls']))} (B4p to B9p re-derive the "
    "classification for 4 to 9 vertices from an empty list; named and regressions are the fixed positive and negative controls).",
    f"- Predictions file sha256 `{report['predictions']['sha256']}` (chronology: {report['predictions']['chronology']}).",
    f"- Environment: {json.dumps(report['environment'], sort_keys=True)}; {report['elapsed_seconds']:.0f} s.",
    "",
    "## The list by edge count",
    "",
    "| edges | minimal forbidden graphs |",
    "|---:|---:|",
    *[f"| {m} | {k} |" for m, k in sorted(by_m.items())],
    "",
    "| minimum degree | graphs |",
    "|---:|---:|",
    *[f"| {d} | {k} |" for d, k in sorted(by_min.items())],
    "",
    f"Maximum degree: {dict(sorted(by_max.items()))}. Certificate types behind the members: "
    f"{dict(sorted(Counter(t for *_, t in rows).items()))}.",
    "",
    "## All members (graph6, edges, degree sequence, certificate type)",
    "",
    "```",
    *[f"{g}  {m:2d}  {ds}  {t}" for g, m, ds, t in rows],
    "```",
    "",
]
open(out_path, "w").write("\n".join(lines))
print(f"WROTE {out_path}: {report['minimal_count']} members")
